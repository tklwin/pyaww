        func trie(_ tag: String) -> MMDTTrieNode {
            // Upstream dereferences a missing tag (would crash); degrade to
            // "never matches" instead.
            tries[tag] ?? MMDTTrieNode()
        }
        // PIPELINE order (rule_segmenter/engine.py).
        pipeline = [
            ("REGION", trie("REGION")),
            ("MONTH", trie("MONTH")),
            ("DAY", trie("DAY")),
            ("REG", trie("REG")),
            ("SWORD", trie("SWORD")),
            ("TITLE", trie("TITLE")),
            ("PRN", trie("PRN")),
            ("MCONJ", trie("MCONJ")),
            ("CONJ", trie("CONJ")),
            ("VEP", trie("VEP")),
            ("SFP", trie("SFP")),
            ("QW", trie("QW")),
            ("POSTP", trie("POSTP")),
            ("CL", trie("CL")),
            ("CLEP", trie("CLEP")),
        ]
    }

    // MARK: Public API

    /// Segments `text` into words: de-space between Myanmar word
    /// characters, then run the mmdt rule pipeline.
    public func segment(_ text: String) -> String {
        guard !MMDTText.trimWhitespace(text).isEmpty else { return "" }
        var chunks = ruleSegment(despaceMyanmar(text))
        chunks = cleanWordnumTag(chunks)
        chunks = mergeNumClassifier(chunks)
        chunks = mergePredicate(chunks)
        chunks = cleanSfpChunks(chunks)
        chunks = cleanClsTag(chunks)
        chunks = cleanPostpTag(chunks)
        chunks = cleanChunks(chunks)
        let tokens = collapseToTokens(chunks)
        var out = tokens.joined(separator: " ")
        out = replaceMatches(attachPattern, in: out, template: "$1")
        out = replaceMatches(whitespaceRunPattern, in: out, template: " ")
        return MMDTText.trimWhitespace(out)
    }

    /// Removes whitespace runs whose neighbours are both Myanmar word
    /// characters (letters/marks; digits and punctuation excluded) — the
    /// Pyaww de-space step (upstream defines such regexes but never uses
    /// them).
    func despaceMyanmar(_ text: String) -> String {
        replaceMatches(despacePattern, in: text, template: "")
    }

    // MARK: Regex helpers

    private func replaceMatches(_ regex: NSRegularExpression, in text: String, template: String) -> String {
        let range = NSRange(location: 0, length: (text as NSString).length)
        return regex.stringByReplacingMatches(in: text, range: range, withTemplate: template)
    }

    /// Python `re.sub` with a function replacement (left-to-right,
    /// non-overlapping matches).
    private func replacingMatches(
        _ regex: NSRegularExpression,
        in text: String,
        _ transform: (NSString, NSTextCheckingResult) -> String
    ) -> String {
        let ns = text as NSString
        var out = ""
        var last = 0
        regex.enumerateMatches(in: text, range: NSRange(location: 0, length: ns.length)) { result, _, _ in
            guard let result else { return }
            out += ns.substring(with: NSRange(location: last, length: result.range.location - last))
            out += transform(ns, result)
            last = result.range.location + result.range.length
        }
        out += ns.substring(from: last)
        return out
    }

    // MARK: Preprocessing (preprocessing/preprocess.py, normalizer.py, cleaner.py)

    private func preprocess(_ text: String) -> ([String], [String: String]) {
        // Step 1: clean text.
        var t = replaceMatches(removeSpecialPattern, in: text, template: " ")
        t = replaceMatches(zeroWidthPrePattern, in: t, template: "")
        t = replaceMatches(whitespaceRunPattern, in: t, template: " ")
        t = MMDTText.trimWhitespace(t.precomposedStringWithCanonicalMapping)

        // Step 2: collapse digit/date/time spacing.
        t = collapseDigitSpaces(t)

        // Step 3: protect patterns.
        var protected: [String: String] = [:]
        var counter = 1
        for pattern in protectPatterns {
            t = replacingMatches(pattern, in: t) { ns, match in
                let key = "\u{02}" + MMDTSegmenter.encodeCounter(counter) + "\u{03}"
                protected[key] = ns.substring(with: match.range)
                counter += 1
                return " \(key) "
            }
        }

        // Step 4: remove unwanted punctuation outside protected. Upstream's
        // "PROT" split pattern never matches the real placeholder format, so
        // it degenerates to a plain global substitution.
        t = replaceMatches(punctRemovePattern, in: t, template: " ")

        // Step 5: split punctuation.
        var tokens: [String] = []
        for token in MMDTText.splitOnWhitespace(t) {
            if protected[token] != nil {
                tokens.append(token)
            } else {
                let split = replaceMatches(punctPattern, in: token, template: " $1 ")
                tokens.append(contentsOf: MMDTText.splitOnWhitespace(split))
            }
        }

        // Step 6: cleanup.
        tokens = tokens.filter { !MMDTText.trimWhitespace($0).isEmpty }
        return (tokens, protected)
    }

    /// `_encode_counter` (preprocess.py): base-16 over SAFE_CHARS
    /// (U+0010–U+001F).
    private static let safeChars: [UnicodeScalar] = (0x10...0x1F).compactMap { UnicodeScalar(UInt32($0)) }

    private static func encodeCounter(_ n: Int) -> String {
        if n == 0 { return String(Character(safeChars[0])) }
        var value = n
        let base = safeChars.count
        var out: [UnicodeScalar] = []
        while value > 0 {
            out.append(safeChars[value % base])
            value /= base
        }
        return String(String.UnicodeScalarView(out.reversed()))
    }

    /// `collapse_digit_spaces` (normalizer.py).
    private func collapseDigitSpaces(_ text: String) -> String {
        var t = replacingMatches(collapseTimePattern, in: text) { ns, match in
            var value = ns.substring(with: match.range(at: 1))
                + ":" + ns.substring(with: match.range(at: 2))
            if match.range(at: 3).location != NSNotFound {
                value += ":" + ns.substring(with: match.range(at: 3))
            }
            return value
        }
        // The upstream long-number rule is a no-op: its match cannot contain
        // whitespace, so "remove spaces inside the match" changes nothing.
        t = replacingMatches(collapseDatePattern, in: t) { ns, match in
            (1...5).map { ns.substring(with: match.range(at: $0)) }.joined()
        }
        return t
    }

    // MARK: Labeling (rule_segmenter/engine.py)

    private func ruleSegment(_ text: String) -> [Chunk] {
        let (phraseTokens, protected) = preprocess(text)
        var tokens: [String] = []
        for phrase in phraseTokens {
            if let original = protected[phrase] {
                tokens.append(original)
            } else {
                tokens.append(contentsOf: syllables.breakIntoSyllables(phrase))
                tokens.append(" ")
            }
        }

        var chunks: [Chunk] = []
        var i = 0
        let n = tokens.count
        while i < n {
            let t = tokens[i]
            if MMDTConfig.skip.contains(t) {
                chunks.append(Chunk(span: (i, i), text: t, tag: "PUNCT"))
                i += 1
                continue
            }
            if let tag = preDefinedTag(t) {
                chunks.append(Chunk(span: (i, i), text: t, tag: tag))
                i += 1
                continue
            }
            if let match = scanLongestAt(tokens, at: i) {
                chunks.append(match)
                i = match.span.1 + 1
            } else {
                chunks.append(Chunk(span: (i, i), text: t, tag: "RAW"))
                i += 1
            }
        }
        return chunks
    }

    /// `_check_pre_defined_tag` — `re.match` semantics (anchored at start,
    /// not necessarily the whole token).
    private func preDefinedTag(_ token: String) -> String? {
        let range = NSRange(location: 0, length: (token as NSString).length)
        for (tag, patterns) in tagPatterns {
            for pattern in patterns
            where pattern.firstMatch(in: token, options: [.anchored], range: range) != nil {
                return tag
            }
        }
        return nil
    }

    /// `scan_longest_at` (scanner.py): longest trie match at position `i`,
    /// across all pipeline tries in priority order.
    private func scanLongestAt(_ tokens: [String], at i: Int) -> Chunk? {
        if MMDTConfig.skip.contains(tokens[i]) { return nil }
        let n = tokens.count
        var bestEnd: Int?
        var bestTag: String?
        var bestText: String?
        for (tag, node) in pipeline {
            var current = node
            var j = i
            var lastEnd: Int?
            while j < n {
                let t = tokens[j]
                if MMDTConfig.skip.contains(t) { break }
                guard let child = current.children[t] else { break }
                current = child
                j += 1
                if current.endTag != nil {
                    lastEnd = j - 1
                }
            }
            if let lastEnd, lastEnd > (bestEnd ?? Int.min) {
                bestEnd = lastEnd
                bestTag = tag  // pipeline entries always override the trie tag
                bestText = tokens[i...lastEnd].joined()
            }
        }
        guard let end = bestEnd, let tag = bestTag, let text = bestText else { return nil }
        return Chunk(span: (i, end), text: text, tag: tag)
    }

    // MARK: Structural merges (rule_segmenter/merge_ops.py)

    private func mergeNumClassifier(_ input: [Chunk]) -> [Chunk] {
        var chunks = input  // upstream mutates tags in place while scanning
        var out: [Chunk] = []
        var i = 0
        let n = chunks.count
        let numberTags: Set<String> = ["NUM", "WORDNUM"]
        let clTags: Set<String> = ["CL", "CLEP"]
        let numPunct: Set<String> = [",", ".", " "]
        while i < n {
            let cur = chunks[i]
            if cur.text == MMDTConfig.percentWord {
                out.append(Chunk(span: cur.span, text: cur.text, tag: "INUMCL"))
                i += 1
                continue
            }
            if numberTags.contains(cur.tag) {
                let numStart = cur.span.0
                var j = i
                var wordnum = 0
                while j < n && (numberTags.contains(chunks[j].tag) || numPunct.contains(chunks[j].text)) {
                    j += 1
                    if j < n && chunks[j].tag == "WORDNUM" { wordnum += 1 }
                }
                if chunks[j - 1].text == MMDTConfig.specialNum && wordnum == 1 { j -= 1 }
                let numText = MMDTText.trimWhitespace(chunks[i..<j].map(\.text).joined())
                    .replacingOccurrences(of: " ", with: "")
                let numEnd = chunks[j - 1].span.1
                out.append(Chunk(span: (numStart, numEnd), text: numText, tag: "NUM"))
                var k = j
                while k < n && (clTags.contains(chunks[k].tag) || MMDTConfig.commonKeysPre.contains(chunks[k].text)) {
                    chunks[k].tag = "NUMCL"
                    out.append(chunks[k])
                    k += 1
                }
                i = k
                continue
            }
            out.append(cur)
            i += 1
        }
        return out
    }

    private func mergePredicate(_ chunks: [Chunk]) -> [Chunk] {
        let n = chunks.count
        var i = n - 1
        var out: [Chunk] = []
        while i >= 0 {
            let cur = chunks[i]
            if MMDTConfig.funTag.contains(cur.tag) {
                out.append(cur)
                i -= 1
                continue
            }
            if cur.tag == "SFP" {
                var j = i
                var negIndex: Int?
                var queIndex: Int?
                var rawIndex: Int?
                while j >= 0 && ["SFP", "VEP", "RAW", "QW"].contains(chunks[j].tag) {
                    if MMDTConfig.specialPostpSfp.contains(chunks[j].text) { break }
                    if chunks[j].text == MMDTConfig.negPrefix && negIndex == nil { negIndex = j }
                    if chunks[j].tag == "QW" && queIndex == nil { queIndex = j }
                    if chunks[j].tag == "RAW" && rawIndex == nil { rawIndex = j }
                    j -= 1
                }
                if i - j > 1 {
                    let start = chunks[j + 1].span.0
                    let end = chunks[i].span.1
                    var text = chunks[(j + 1)...i].map(\.text).joined()
                    if let neg = negIndex, MMDTConfig.negSentSfp.contains(chunks[i].text) {
                        text = chunks[neg...i].map(\.text).joined()
                        let predStart = chunks[neg].span.0
                        out.append(Chunk(span: (predStart, end), text: text, tag: "PRED"))
                        text = sliceText(chunks, j + 1, neg)
                        let rawEnd = chunk(chunks, neg - 1).span.1
                        out.append(Chunk(span: (start, rawEnd), text: text, tag: "RAW"))
                    } else if let que = queIndex, MMDTConfig.queSentSfp.contains(chunks[i].text) {
                        text = chunks[que...i].map(\.text).joined()
                        let predStart = chunks[que].span.0
                        out.append(Chunk(span: (predStart, end), text: text, tag: "PRED"))
                        text = sliceText(chunks, j + 1, que)
                        let queEnd = chunk(chunks, que - 1).span.1
                        out.append(Chunk(span: (start, queEnd), text: text, tag: "RAW"))
                    } else if let raw = rawIndex {
                        text = chunks[(raw + 1)...i].map(\.text).joined()
                        let predStart = chunks[raw + 1].span.0
                        out.append(Chunk(span: (predStart, end), text: text, tag: "PRED"))
                        text = sliceText(chunks, j + 1, raw + 1)
                        let rawEnd = chunks[raw + 1].span.1
                        out.append(Chunk(span: (start, rawEnd), text: text, tag: "RAW"))
                    } else {
                        let predStart = chunks[j + 1].span.0
                        out.append(Chunk(span: (predStart, end), text: text, tag: "PRED"))
                    }
                    i = j
                    continue
                }
            }
            out.append(cur)
            i -= 1
        }
        return out.reversed()
    }

    /// Python `"".join(ch.text for ch in chunks[lo:hi])`.
    private func sliceText(_ chunks: [Chunk], _ lo: Int, _ hi: Int) -> String {
        guard lo < hi else { return "" }
        return chunks[lo..<hi].map(\.text).joined()
    }

    /// Python list indexing (negative indices wrap from the end — upstream
    /// can evaluate `chunks[neg_index - 1]` with `neg_index == 0`).
    private func chunk(_ chunks: [Chunk], _ index: Int) -> Chunk {
        index < 0 ? chunks[chunks.count + index] : chunks[index]
    }

    // MARK: Cleaners (rule_segmenter/cleanner.py)

    private func cleanWordnumTag(_ chunks: [Chunk]) -> [Chunk] {
        let maxTokens = 5
        var out: [Chunk] = []
        var i = 0
        let n = chunks.count
        while i < n {
            let cur = chunks[i]

            // Rule 1: percent word 'ရာခိုင်နှုန်း' (possibly split across
            // up to 5 tokens) -> one INUMCL chunk.
            var txt = ""
            var k = 0
            var end: Int?
            while i + k < n && k < maxTokens && chunks[i + k].tag != "PUNCT" {
                txt += chunks[i + k].text
                k += 1
                if txt == MMDTConfig.percentWord || txt.hasPrefix(MMDTConfig.percentWord) {
                    end = i + k
                    break
                }
            }
            if let end {
                let spanStart = chunks[i].span.0
                let spanEnd = chunks[end - 1].span.1
                out.append(Chunk(span: (spanStart, spanEnd), text: MMDTConfig.percentWord, tag: "INUMCL"))
                i = end
                continue
            }

            // Rule 2: isolated WORDNUM -> RAW.
            var finalTag = cur.tag
            if cur.tag == "WORDNUM" {
                var p = i - 1
                while p >= 0 && chunks[p].tag == "PUNCT" { p -= 1 }
                var q = i + 1
                while q < n && chunks[q].tag == "PUNCT" { q += 1 }
                let prev = p >= 0 ? chunks[p] : nil
                let next = q < n ? chunks[q] : nil
                let prevIsNum = prev.map { ["NUM", "WORDNUM"].contains($0.tag) } ?? false
                let nextIsNum = next.map {
                    ["NUM", "WORDNUM", "CL"].contains($0.tag) || MMDTConfig.commonKeysPre.contains($0.text)
                } ?? false
                if !prevIsNum && !nextIsNum { finalTag = "RAW" }
            }
            out.append(Chunk(span: cur.span, text: cur.text, tag: finalTag))
            i += 1
        }
        return out
    }

    private func cleanClsTag(_ chunks: [Chunk]) -> [Chunk] {
        var out: [Chunk] = []
        for (i, cur) in chunks.enumerated() {
            var finalTag = cur.tag
            if ["CL", "VEP"].contains(cur.tag)
                || MMDTConfig.pnumCl.contains(cur.text)
                || MMDTConfig.regionCl.contains(cur.text)
                || MMDTConfig.nounCl.contains(cur.text) {
                let prevTag = i > 0 ? chunks[i - 1].tag : nil
                let nextTag = i + 1 < chunks.count ? chunks[i + 1].tag : nil
                if let prevTag, ["DAY", "DATE"].contains(prevTag), MMDTConfig.dayCl.contains(cur.text) {
                    finalTag = "DAYCL"
                }
                if prevTag == "MONTH" && MMDTConfig.mthCl.contains(cur.text) {
                    finalTag = "MONTHCL"
                }
                if (prevTag == "REGION" && MMDTConfig.regionOneWord.contains(cur.text))
                    || MMDTConfig.regionCl.contains(cur.text) {
                    finalTag = "REGIONCL"
                }
                if MMDTConfig.nounCl.contains(cur.text) {
                    finalTag = "NOUNCL"
                }
                if let nextTag, ["NUM", "WORDNUM"].contains(nextTag), MMDTConfig.pnumCl.contains(cur.text) {
                    finalTag = "INUMCL"
                }
            }
            out.append(Chunk(span: cur.span, text: cur.text, tag: finalTag))
        }
        return out
    }

    private func cleanPostpTag(_ chunks: [Chunk]) -> [Chunk] {
        var out: [Chunk] = []
        var i = 0
        let n = chunks.count
        while i < n {
            let ch = chunks[i]
            if MMDTConfig.specialPostp.contains(ch.text) {
                // Upstream guards with `i-1 > 0` / `i-2 > 0` (not >=), so
                // chunk 0 is never treated as "previous" — mirrored.
                let prevTag = i - 1 > 0 ? chunks[i - 1].tag : nil
                let prevText = i - 1 > 0 ? chunks[i - 1].text : ""
                let prevPrevTag = i - 2 > 0 ? chunks[i - 2].tag : nil
                let prevPrevText = i - 2 > 0 ? chunks[i - 2].text : ""
                if i == 0
                    || (prevTag == "POSTP" && prevText == ch.text)
                    || prevText == "အ"
                    || (prevTag == "PUNCT" && prevPrevTag == "POSTP" && prevPrevText == ch.text) {
                    out.append(Chunk(span: ch.span, text: ch.text, tag: "RAW"))
                    i += 1
                    continue
                }
            }
            out.append(ch)
            i += 1
        }
        return out
    }

    private func cleanSfpChunks(_ chunks: [Chunk]) -> [Chunk] {
        var out: [Chunk] = []
        var i = 0
        let n = chunks.count
        while i < n {
            var cur = chunks[i]
            if cur.tag == "CONJ", MMDTConfig.negSentSfp.contains(cur.text),
               let last = out.last, last.tag == "PRED" {
                let prev = out.removeLast()
                out.append(Chunk(span: (prev.span.0, cur.span.1),
                                 text: prev.text + cur.text, tag: "PRED"))
                i += 1
                continue
            }
            var q = i + 1
            while q < n && chunks[q].tag == "PUNCT" { q += 1 }
            let nextTag = q < n ? chunks[q].tag : nil
            if cur.tag == "SFP" && MMDTConfig.isolatedSfpToPostp.contains(cur.text) {
                var p = out.count - 1
                while p >= 0 && out[p].tag == "PUNCT" { p -= 1 }
                let prevTag = p >= 0 ? out[p].tag : nil
                if !["PRED", "SFP", "VEP"].contains(prevTag ?? "")
                    && !["PRED", "SFP"].contains(nextTag ?? "") {
                    cur = Chunk(span: cur.span, text: cur.text, tag: "POSTP")
                }
            }
            out.append(cur)
            i += 1
        }
        return out
    }

    private func cleanChunks(_ chunks: [Chunk]) -> [Chunk] {
        var cleaned: [Chunk] = []
        for ch in chunks {
            let newText = replaceMatches(cleanZeroWidthPattern, in: ch.text, template: "")
            if !newText.isEmpty {
                cleaned.append(Chunk(span: ch.span, text: newText, tag: ch.tag))
            }
        }
        return cleaned
    }

    // MARK: Collapse (rule_segmenter/collapse.py, Pyaww-patched)

    /// Upstream `collapse_to_phrase_chunks` token output with Pyaww's
    /// punctuation fix: every non-space punctuation token is kept (upstream
    /// drops `,` `?` `!` `၊`, and keeps `။` only when a phrase precedes it).
    private func collapseToTokens(_ chunks: [Chunk]) -> [String] {
        var surface: [String] = []
        var bufText: [String] = []
        var bufStart: Int?
        var bufEnd: Int?

        func flush() {
            guard !bufText.isEmpty, bufStart != nil, bufEnd != nil else { return }
            surface.append(bufText.joined())
            bufText = []
            bufStart = nil
            bufEnd = nil
        }

        for ch in chunks {
            if ch.tag == "PUNCT" {
                if ch.text == " " || ch.text == "" {
                    flush()
                } else {
                    flush()
                    surface.append(ch.text)
                }
                continue
            }
            if MMDTConfig.funTag.contains(ch.tag) || MMDTConfig.specialPostpSfp.contains(ch.text) {
                if MMDTConfig.specialAdj.contains(ch.text) {
                    // Include in the current phrase, then flush immediately.
                    if bufStart == nil { bufStart = ch.span.0 }
                    bufEnd = ch.span.1
                    bufText.append(ch.text)
                    flush()
                } else {
                    flush()
                    surface.append(ch.text)
                }
                continue
            }
            if bufStart == nil { bufStart = ch.span.0 }
            bufEnd = ch.span.1
            bufText.append(ch.text)
        }
        flush()
        return surface.filter { $0 != " " && $0 != "" }
    }
}

// MARK: - Text helpers

/// The parts of CPython string behaviour the reference pipeline relies on.
///
/// Deliberate deviation: CPython's `str.split()/strip()` also treat
/// U+001C–U+001F as whitespace, and those characters are exactly part of the
/// upstream protection-placeholder alphabet — upstream can therefore split a
/// placeholder apart once ≥ 12 protections occur in one text. This port uses
/// Unicode White_Space only, which keeps placeholders intact. All frozen
/// reference vectors use fewer than 5 protections, where behaviour matches.
enum MMDTText {
    static func trimWhitespace(_ text: String) -> String {
        var sub = Substring(text)
        while let first = sub.first, first.isWhitespace { sub = sub.dropFirst() }
        while let last = sub.last, last.isWhitespace { sub = sub.dropLast() }
        return String(sub)
    }

    static func splitOnWhitespace(_ text: String) -> [String] {
        text.split(whereSeparator: \.isWhitespace).map(String.init)
    }
}

private func compileRegex(_ pattern: String, _ name: String) throws -> NSRegularExpression {
    do {
        return try NSRegularExpression(pattern: pattern)
    } catch {
        throw MMDTSegmenter.InitError(description: "invalid regex \(name): \(error)")
    }
}
