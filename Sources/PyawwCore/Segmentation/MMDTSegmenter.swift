import Foundation

/// Swift port of mmdt-tokenizer 0.1.3 (MIT, Myanmar Data Tech) — rule-based
/// Myanmar word segmentation, with two documented Pyaww adaptations:
///
///  * the input is de-spaced between Myanmar word characters first (the ASR
///    emits syllable-level spacing, and the lexicon cannot match across
///    spaces);
///  * punctuation is preserved: upstream silently drops `,` `?` `!` and `၊`
///    from its token stream and space-separates `။`; this port keeps every
///    punctuation token, attached to the preceding word.
///
/// The behaviour is frozen as `input<TAB>expected` pairs in
/// `Tests/Fixtures/segmentation/vectors.tsv`, generated by
/// `scripts/generate_seg_vectors.py` (the upstream Python package with the
/// same adaptations). Method-by-method mapping to upstream files is noted
/// per section below.
public final class MMDTSegmenter {
    public struct InitError: Error, CustomStringConvertible {
        public let description: String
    }

    private struct Chunk {
        var span: (Int, Int)
        var text: String
        var tag: String
    }

    // MARK: Stored state

    private let syllableBreakPattern: NSRegularExpression
    private let punctPattern: NSRegularExpression
    private let removeSpecialPattern: NSRegularExpression
    private let zeroWidthPrePattern: NSRegularExpression
    private let whitespaceRunPattern: NSRegularExpression
    private let collapseTimePattern: NSRegularExpression
    private let collapseDatePattern: NSRegularExpression
    private let punctRemovePattern: NSRegularExpression
    private let cleanZeroWidthPattern: NSRegularExpression
    private let despacePattern: NSRegularExpression
    private let attachPattern: NSRegularExpression
    private let protectPatterns: [NSRegularExpression]
    private let tagPatterns: [(tag: String, patterns: [NSRegularExpression])]

    private let syllables: MyanmarSyllables
    private let pipeline: [(tag: String, node: MMDTTrieNode)]

    /// Where the bundled lexicon was loaded from (diagnostics/tests).
    public let lexiconURL: URL

    // MARK: Init

    public init() throws {
        let email = try compileRegex(MMDTConfig.emailPattern, "emailPattern")
        let url = try compileRegex(MMDTConfig.urlPattern, "urlPattern")
        let perName = try compileRegex(MMDTConfig.perNamePattern, "perNamePattern")
        let title = try compileRegex(MMDTConfig.titlePattern, "titlePattern")
        let abbEng = try compileRegex(MMDTConfig.abbEngPattern, "abbEngPattern")
        let abbBur1 = try compileRegex(MMDTConfig.abbBurPattern1, "abbBurPattern1")
        let abbBur2 = try compileRegex(MMDTConfig.abbBurPattern2, "abbBurPattern2")
        let date01 = try compileRegex(MMDTConfig.datePattern01, "datePattern01")
        let date02 = try compileRegex(MMDTConfig.datePattern02, "datePattern02")
        let time = try compileRegex(MMDTConfig.timePattern, "timePattern")
        let decNum = try compileRegex(MMDTConfig.decNumPattern, "decNumPattern")
        let longNum = try compileRegex(MMDTConfig.longNumPattern, "longNumPattern")
        let frcNum = try compileRegex(MMDTConfig.frcNumPattern, "frcNumPattern")
        let phone = try compileRegex(MMDTConfig.phoneNumPattern, "phoneNumPattern")
        let possessive = try compileRegex(MMDTConfig.possessivePattern, "possessivePattern")
        let wordNum = try compileRegex(MMDTConfig.wordNumPattern, "wordNumPattern")
        let number = try compileRegex(MMDTConfig.numberPattern, "numberPattern")

        // PROTECT_PATTERNS order (utils/patterns.py).
        protectPatterns = [
            email, url, perName,
            title, abbEng, abbBur1, abbBur2,
            date01, date02, time,
            decNum, longNum, frcNum,
            phone, possessive, wordNum, number,
        ]
        // TAG_PATTERNS order (utils/patterns.py).
        tagPatterns = [
            ("NUM", [number, phone]),
            ("WORDNUM", [wordNum]),
            ("ORG", [abbBur1, abbBur2, abbEng]),
            ("NAME", [perName]),
            ("DATE", [date01, date02]),
            ("TIME", [time]),
            ("EMAIL", [email]),
            ("URL", [url]),
        ]

        syllableBreakPattern = try compileRegex(MMDTConfig.syllableBreakPattern, "syllableBreakPattern")
        punctPattern = try compileRegex(MMDTConfig.punctPattern, "punctPattern")
        removeSpecialPattern = try compileRegex(MMDTConfig.removeSpecialPattern, "removeSpecialPattern")
        zeroWidthPrePattern = try compileRegex(MMDTConfig.zeroWidthPrePattern, "zeroWidthPrePattern")
        whitespaceRunPattern = try compileRegex(MMDTConfig.whitespaceRunPattern, "whitespaceRunPattern")
        collapseTimePattern = try compileRegex(MMDTConfig.collapseTimePattern, "collapseTimePattern")
        collapseDatePattern = try compileRegex(MMDTConfig.collapseDatePattern, "collapseDatePattern")
        punctRemovePattern = try compileRegex(MMDTConfig.punctRemovePattern, "punctRemovePattern")
        cleanZeroWidthPattern = try compileRegex(MMDTConfig.cleanZeroWidthPattern, "cleanZeroWidthPattern")
        despacePattern = try compileRegex(MMDTConfig.despacePattern, "despacePattern")
        attachPattern = try compileRegex(MMDTConfig.attachPattern, "attachPattern")

        syllables = MyanmarSyllables(breakPattern: syllableBreakPattern)

        guard let lexiconURL = PyawwCoreResources.lexiconsURL() else {
            throw InitError(description: "lexicons.json was not found (PyawwCore resource bundle)")
        }
        self.lexiconURL = lexiconURL
        let tries: [String: MMDTTrieNode]
        do {
            tries = try MMDTLexicon.load(from: lexiconURL)
