#!/usr/bin/env python3
"""Generate MMDTConfig.swift — exact-port constants for the mmdt-tokenizer
Swift port (Phase 4). Emits lexicon tuples and regex sources from
mmdt-tokenizer 0.1.3 as Swift string literals (every non-ASCII character
code-point-escaped), so invisible characters (e.g. the ZWJ variants in
SPECIAL_ADJ) survive transcription exactly.

Requires: a venv with mmdt-tokenizer==0.1.3.
Usage:    <venv>/bin/python scripts/generate_mmdt_config.py
"""
from pathlib import Path

import mmdt_tokenizer.rule_segmenter.config as cfg
import mmdt_tokenizer.utils.patterns as pat

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "Sources/PyawwCore/Segmentation/MMDTConfig.swift"


def lit(s: str) -> str:
    out = '"'
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out += '\\"'
        elif ch == "\\":
            out += "\\\\"
        elif 0x20 <= o < 0x7F:
            out += ch
        else:
            out += f"\\u{{{o:04X}}}"
    return out + '"'


def icu(pattern: str) -> str:
    """Make the pattern parse identically under ICU (NSRegularExpression).

    The upstream syllable pattern spells the ASCII punctuation block as
    ``!-/:-@[-`{-~``; ICU rejects the ``[-` `` range as written, so it is
    replaced with explicit ``\\u`` escapes.
    """
    return pattern.replace(
        "!-/:-@[-`{-~",
        "\\u0021-\\u002F\\u003A-\\u0040\\u005B-\\u0060\\u007B-\\u007E",
    )


def string_const(name: str, value: str) -> str:
    return f"    static let {name} = {lit(icu(value))}\n"


def array_const(name: str, values) -> str:
    return f"    static let {name}: [String] = [{', '.join(lit(v) for v in values)}]\n"


lines = []
lines.append("// Generated by scripts/generate_mmdt_config.py from mmdt-tokenizer 0.1.3\n")
lines.append("// (MIT, Myanmar Data Tech — see docs/third-party.md). Do not edit by hand.\n")
lines.append("import Foundation\n\n")
lines.append("enum MMDTConfig {\n")

lines.append("    // Word-segmenter config (rule_segmenter/config.py)\n")
lines.append(array_const("skip", sorted(cfg.SKIP)))
lines.append(array_const("funTag", cfg.FUN_TAG))
lines.append(array_const("negSentSfp", cfg.NEG_SENT_SFP))
lines.append(array_const("queSentSfp", cfg.QUE_SENT_SFP))
lines.append(string_const("negPrefix", cfg.NEG_PREFIX))
lines.append(array_const("isolatedSfpToPostp", cfg.ISOLATED_SFP_TO_POSTP))
lines.append(array_const("specialPostp", cfg.SPECIAL_POSTP))
lines.append(string_const("specialNum", cfg.SPECIAL_NUM))
lines.append(array_const("specialAdj", cfg.SPECIAL_ADJ))
lines.append(array_const("specialPostpSfp", cfg.SPECIAL_POSTP_SFP))
lines.append(string_const("percentWord", cfg.PERCENT_WORD))
lines.append(array_const("commonKeysPre", cfg.COMMON_KEYS_PRE))
lines.append(array_const("dayCl", cfg.DAY_CL))
lines.append(array_const("mthCl", cfg.MTH_CL))
lines.append(array_const("pnumCl", cfg.PNUM_CL))
lines.append(array_const("nounCl", cfg.NOUN_CL))
lines.append(array_const("regionCl", cfg.REGION_CL))
lines.append(array_const("regionOneWord", cfg.REGION_ONE_WORD))

lines.append("\n    // Regex sources (utils/patterns.py, taken from the compiled patterns)\n")
for name, rx in [
    ("syllableBreakPattern", pat.SYLLABLE_BREAK_PATTERN),
    ("punctPattern", pat.PUNCT_PATTERN),
    ("emailPattern", pat.EMAIL_PATTERN),
    ("urlPattern", pat.URL_PATTERN),
    ("perNamePattern", pat.PER_NAME_PATTERN),
    ("titlePattern", pat.TITLE_PATTERN),
    ("abbEngPattern", pat.ABB_ENG_PATTERN),
    ("abbBurPattern1", pat.ABB_BUR_PATTERN_1),
    ("abbBurPattern2", pat.ABB_BUR_PATTERN_2),
    ("datePattern01", pat.DATE_PATTERN_01),
    ("datePattern02", pat.DATE_PATTERN_02),
    ("timePattern", pat.TIME_PATTERN),
    ("decNumPattern", pat.DEC_NUM_PATTERN),
    ("longNumPattern", pat.LONG_NUM_PATTERN),
    ("frcNumPattern", pat.FRC_NUM_PATTERN),
    ("numberPattern", pat.NUMBER_PATTERN),
    ("wordNumPattern", pat.WORD_NUM_PATTERN),
    ("phoneNumPattern", pat.PHONE_NUM_PATTERN),
    ("possessivePattern", pat.POSSESIVE_PATTERN),
]:
    lines.append(string_const(name, rx.pattern))

lines.append("\n    // Inline regexes from preprocessing/preprocess.py & normalizer.py\n")
D = r"0-9\u1040-\u1049"
lines.append(string_const("removeSpecialPattern", r"[~^*_+=<>\[\]{}|\\…“”‘’「」『』\"'#()]+|\.\.+"))
lines.append(string_const("zeroWidthPrePattern", r"[\u200B\u200C\u200D\uFEFF]"))
lines.append(string_const("whitespaceRunPattern", r"\s+"))
lines.append(string_const("collapseTimePattern",
                          rf"([{D}]{{1,2}})\s*:\s*([{D}]{{2}})(?:\s*:\s*([{D}]{{2}}))?"))
lines.append(string_const("collapseDatePattern",
                          rf"([{D}]{{1,2}})\s*([/\-\.])\s*([{D}]{{1,2}})\s*([/\-\.])\s*([{D}]{{2,4}})"))
lines.append(string_const("punctRemovePattern", r"[-:/]"))
lines.append(string_const("cleanZeroWidthPattern", r"[\u200b\ufeff\u2060]"))

lines.append("\n    // Pyaww adaptations (documented in docs/thread: de-space + punctuation)\n")
DSC = r"\u1000-\u103F\u1050-\u1097\uA9E0-\uA9EF\uAA60-\uAA7A"
lines.append(string_const("despacePattern", rf"(?<=[{DSC}])\s+(?=[{DSC}])"))
lines.append(string_const("attachPattern", r"\s+([၊။,?!])"))
lines.append("}\n")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("".join(lines), encoding="utf-8")
print(f"wrote {OUT.relative_to(REPO)} ({OUT.stat().st_size} bytes)")
